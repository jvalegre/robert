import os
import re
import pandas as pd
import matplotlib.pyplot as plt


class PredictionsTab(QWidget):
    """Tab for displaying prediction results from ROBERT runs."""

    availabilityChanged = Signal(bool)

    def __init__(self, parent=None):
        super().__init__(parent)

        self._thread_pool = QThreadPool.globalInstance()

        layout = QVBoxLayout(self)

        self.placeholder = QLabel("No prediction data available")
        self.placeholder.setAlignment(Qt.AlignCenter)
        layout.addWidget(self.placeholder)

        self.subtabs = QTabWidget()
        self.subtabs.hide()
        layout.addWidget(self.subtabs)

    # --------------------------------------------------
    def _extract_names_column_from_predict(self):
        """
        Looks for PREDICT_data.dat inside the PREDICT folder
        under the current run directory and extracts the value
        passed to --names in the command line.
        """
        base_path = self._base_path

        if os.path.isfile(base_path):
            base_path = os.path.dirname(base_path)

        predict_dir = os.path.join(base_path, "PREDICT")
        dat_path = os.path.join(predict_dir, "PREDICT_data.dat")

        if not os.path.exists(dat_path):
            return None

        with open(dat_path, "r", encoding="utf-8") as f:
            content = f.read()

        match = re.search(r'--names\s+"([^"]+)"', content)
        if match:
            return match.group(1)

        return None

    def _filter_prediction_dataframe(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Keeps and orders columns as:
        1. names column (if available)
        2. SMILES / smiles (if available)
        3. *_pred
        4. *_pred_sd
        """

        names_col = self._extract_names_column_from_predict()

        smiles_cols = []
        pred_cols = []
        pred_sd_cols = []

        for col in df.columns:
            if col.lower() == "smiles":
                smiles_cols.append(col)
            elif col.endswith("_pred"):
                pred_cols.append(col)
            elif col.endswith("_pred_sd"):
                pred_sd_cols.append(col)

        ordered_columns = []

        # Add Image column if smiles exists
        if smiles_cols:
            ordered_columns.append("Image")

        if names_col and names_col in df.columns:
            ordered_columns.append(names_col)

        ordered_columns.extend(smiles_cols)
        ordered_columns.extend(pred_cols)
        ordered_columns.extend(pred_sd_cols)

        if not ordered_columns:
            return df

        df = df.copy()

        if smiles_cols:
            df.insert(0, "Image", df[smiles_cols[0]])

        return df[ordered_columns]

    def refresh_with_new_path(self, selected_file_path: str):
        """Refreshes the predictions tab with new data from the selected file path."""
        # This is the ONLY base path used by PredictionsTab
        self._base_path = selected_file_path

        csvs = find_prediction_csvs(selected_file_path)

        self.subtabs.clear()

        if not csvs:
            self.subtabs.hide()
            self.placeholder.show()
            self.availabilityChanged.emit(False)
            return

        for key, path in csvs.items():
            container = QLabel("Loading CSV…")
            container.setAlignment(Qt.AlignCenter)
            self.subtabs.addTab(container, key.replace("_", " "))

            task = LoadCsvTask(key, path)
            task.signals.done.connect(self._add_loaded_df)
            self._thread_pool.start(task)

        self.placeholder.hide()
        self.subtabs.show()
        self.availabilityChanged.emit(True)

    def _add_loaded_df(self, key: str, df: pd.DataFrame):
        """Adds a dataframe to the predictions tab."""

        # Filter dataframe columns
        df = self._filter_prediction_dataframe(df)

        info = evaluate_predictions_for_model(
            self._base_path,
            df,
            key,  # "PFI" or "No_PFI"
        )

        # Extract fragment image
        pdf_path = get_robert_report_path(self._base_path)
        pdf_image = extract_robert_fragment_image(pdf_path, key)

        widget = self._create_table_with_stats(df, info, pdf_image)
        tab_name = key.replace("_", " ")

        for i in range(self.subtabs.count()):
            if self.subtabs.tabText(i) == tab_name:
                self.subtabs.removeTab(i)
                self.subtabs.insertTab(i, widget, tab_name)
                break

    # --------------------------------------------------
    def _show_histogram_menu_header(self, pos, df: pd.DataFrame, header):
        """Shows a histogram for the clicked column."""

        column = header.logicalIndexAt(pos)
        if column < 0:
            return

        col_name = df.columns[column]
        series = df[col_name]

        if not pd.api.types.is_numeric_dtype(series):
            QMessageBox.information(self, "Histogram", "Column is not numeric")
            return

        menu = QMenu(header)
        action = menu.addAction(f"Show histogram: {col_name}")

        if menu.exec(header.mapToGlobal(pos)) == action:
            self._show_histogram(series, col_name)

    def _create_table_with_stats(self, df, info, pdf_image):
        """Creates the main table view with the predictions and the side dashboard with stats and diagnostics."""

        # ---- Container ----
        container = QWidget()
        container.setStyleSheet("background: palette(window);")

        layout = QHBoxLayout(container)
        layout.setContentsMargins(0, 0, 0, 0)

        # ---- Table ----
        table = QTableView()

        base_model = PandasTableModel(df)
        proxy = NumericSortProxy()
        proxy.setSourceModel(base_model)
        table.setModel(proxy)

        table.verticalHeader().setDefaultSectionSize(130)
        table.setIconSize(QSize(120, 120))
        table.setSortingEnabled(True)
        table.setSelectionBehavior(QTableView.SelectItems)
        table.setSelectionMode(QTableView.ExtendedSelection)

        header = StatsHeader(df, Qt.Horizontal, table)
        table.setHorizontalHeader(header)

        header.setSectionResizeMode(QHeaderView.ResizeToContents)
        table.resizeColumnsToContents()
        header.setSectionResizeMode(QHeaderView.Interactive)

        if "Image" in df.columns:
            image_col = df.columns.get_loc("Image")
            table.setColumnWidth(image_col, 140)

        header.setContextMenuPolicy(Qt.CustomContextMenu)
        header.customContextMenuRequested.connect(
            lambda pos, d=df, h=header: self._show_header_menu(pos, d, h)
        )

        # ---- Side Dashboard ----
        pdf_path = info["pdf_path"]
        model_key = info["model"]  # "PFI" or "No_PFI"

        # Extrapolation data
        extrap_scores = extract_extrapolation_scores(pdf_path)
        extrap_pixmap = extract_extrapolation_fragment(pdf_path, model_key)

        # External validation plot
        external_pixmaps = find_external_test_pixmaps(self._base_path)
        external_pixmap = external_pixmaps.get(model_key)

        side_panel = PredictionDashboardPanel(
            scenario=info["scenario"],
            pdf_image=pdf_image,
            extrapolation_score=extrap_scores.get(model_key),
            extrapolation_image=extrap_pixmap,
            external_plot=external_pixmap,
        )

        # ---- Separator ----
        separator = QFrame()
        separator.setFixedWidth(1)
        separator.setSizePolicy(QSizePolicy.Fixed, QSizePolicy.Expanding)
        separator.setStyleSheet("background-color: palette(mid);")

        layout.addWidget(table, stretch=3)
        layout.addWidget(separator)
        layout.addWidget(side_panel, stretch=1)

        return container

    def _show_header_menu(self, pos, df: pd.DataFrame, header):
        """Shows a context menu for the table header with sorting and histogram options."""
        column = header.logicalIndexAt(pos)
        if column < 0:
            return

        col_name = df.columns[column]
        series = df[col_name]

        table = header.parent()  # QTableView

        menu = QMenu(header)

        # Sorting actions
        action_sort_asc = menu.addAction("Sort ascending")
        action_sort_desc = menu.addAction("Sort descending")

        menu.addSeparator()

        # Histogram action (only for numeric columns)
        action_hist = None
        if pd.api.types.is_numeric_dtype(series):
            action_hist = menu.addAction(f"Show histogram: {col_name}")

        chosen = menu.exec(header.mapToGlobal(pos))

        if chosen == action_sort_asc:
            table.sortByColumn(column, Qt.AscendingOrder)

        elif chosen == action_sort_desc:
            table.sortByColumn(column, Qt.DescendingOrder)

        elif action_hist is not None and chosen == action_hist:
            self._show_histogram(series, col_name)

    # --------------------------------------------------

    def _show_histogram_menu(self, pos, df: pd.DataFrame, table: QTableView):
        """Shows a context menu for the table header with sorting and histogram options."""
        index = table.indexAt(pos)
        if not index.isValid():
            return

        col_name = df.columns[index.column()]
        series = df[col_name]

        if not pd.api.types.is_numeric_dtype(series):
            QMessageBox.information(self, "Histogram", "Column is not numeric")
            return

        menu = QMenu(table)
        action = menu.addAction(f"Show histogram: {col_name}")

        if menu.exec(table.viewport().mapToGlobal(pos)) == action:
            self._show_histogram(series, col_name)

    # --------------------------------------------------
    def _show_histogram(self, series: pd.Series, col_name: str):
        """Displays a histogram for the given numeric series."""
        clean = series.dropna()

        plt.figure()
        clean.hist(bins=30)

        plt.title(col_name)
        plt.xlabel(col_name)
        plt.ylabel("Frequency")
        plt.grid(False)
        plt.show(block=False)
