"""
Results PDF viewer for ROBERT reports.

This module provides a responsive interface to explore generated PDF reports
within the GUI. It avoids blocking the UI by loading metadata and rendering
pages asynchronously.

Responsibilities:
- Discover and manage PDF reports generated by the workflow
- Create lightweight tab placeholders for each report
- Load PDF metadata (page count, sizes) in background threads
- Render only visible pages on demand (lazy rendering)
- Cache rendered pages and discard outdated renders on zoom changes

Architecture:
- Uses QRunnable tasks (RenderTask, MetaTask) executed via QThreadPool
- Applies a generation-based system to cancel stale render operations
- Computes visible page ranges to minimize unnecessary rendering

Import strategy:
- Supports dual execution modes:
  1. Local (portable execution)
  2. Installed package (environment / entry point)

- Imports use a try/except fallback to ensure compatibility.

Notes:
- Designed for performance with large PDF files
- Rendering is viewport-driven to avoid excessive memory and CPU usage
- Acts as a self-contained viewer independent from the main application logic
"""

