def _read_best_model_pair(best_dir):
    """Load the params CSV and its *_db.csv pair; glob order is filesystem-dependent."""
    paths = glob.glob(os.path.join(best_dir, "*.csv"))
    assert len(paths) == 2
    db_paths = [p for p in paths if os.path.basename(p).endswith("_db.csv")]
    params_paths = [p for p in paths if p not in db_paths]
    assert len(db_paths) == 1 and len(params_paths) == 1
    return pd.read_csv(params_paths[0], encoding="utf-8"), pd.read_csv(
        db_paths[0], encoding="utf-8"
    )


def _model_tag(test_job):
    """ML model name for single-model GENERATE test jobs."""
    return {
        "reduced_gp": "GP",
        "reduced_adab": "ADAB",
        "reduced_xgb": "XGB",
        "reduced_vr": "VR",
        "reduced_vr_clas": "VR",
        "reduced_clas": "RF",
    }.get(test_job, "RF")


def _read_model_pair(generate_dir, folder, model, *, pfi=False):
    """Load params and *_db.csv for a specific model under Raw_data."""
    suffix = f"{model}_PFI" if pfi else model
    params_path = os.path.join(generate_dir, "Raw_data", folder, f"{suffix}.csv")
    db_path = os.path.join(generate_dir, "Raw_data", folder, f"{suffix}_db.csv")
    assert os.path.isfile(params_path), params_path
    assert os.path.isfile(db_path), db_path
    return pd.read_csv(params_path, encoding="utf-8"), pd.read_csv(
        db_path, encoding="utf-8"
    )


